[CmdletBinding()]
param(
    [ValidateRange(10, 1800)][int]$DurationSeconds = 120,
    [string]$OutputDirectory = (Join-Path (Split-Path -Parent $PSScriptRoot) 'data/raw'),
    [uri]$LocalHttpUrl
)
$ErrorActionPreference = 'Stop'
if ($null -ne $LocalHttpUrl) {
    $address = $null
    if ($LocalHttpUrl.Scheme -ne 'http' -or $LocalHttpUrl.UserInfo -or
        -not [Net.IPAddress]::TryParse($LocalHttpUrl.Host, [ref]$address) -or
        $address.AddressFamily -ne [Net.Sockets.AddressFamily]::InterNetwork) {
        throw 'LocalHttpUrl must be a credential-free http URL with a private/loopback IPv4 address.'
    }
    $octets = $address.GetAddressBytes()
    $private = ($octets[0] -eq 10) -or ($octets[0] -eq 127) -or
        ($octets[0] -eq 192 -and $octets[1] -eq 168) -or
        ($octets[0] -eq 172 -and $octets[1] -ge 16 -and $octets[1] -le 31)
    if (-not $private) { throw 'Use only the private lab HTTP server address.' }
}
$runId = 'BENIGN-' + [DateTime]::UtcNow.ToString('yyyyMMddTHHmmssfffZ') + '-' + [Guid]::NewGuid().ToString('N').Substring(0, 8)
$outPath = Join-Path $OutputDirectory $runId
New-Item -ItemType Directory -Path $outPath -ErrorAction Stop | Out-Null
$started = [DateTime]::UtcNow
$deadline = $started.AddSeconds($DurationSeconds)
$iterations = 0
while ([DateTime]::UtcNow -lt $deadline) {
    $iterations++
    "Local benign collection check $iterations" | Set-Content -LiteralPath (Join-Path $outPath 'workload.txt') -Encoding UTF8
    Get-Content -LiteralPath (Join-Path $outPath 'workload.txt') | Out-Null
    Get-Process | Select-Object -First 5 Name,Id | Out-Null
    Get-FileHash -LiteralPath (Join-Path $env:SystemRoot 'System32/notepad.exe') -Algorithm SHA256 | Out-Null
    & (Join-Path $env:SystemRoot 'System32/cmd.exe') /d /c 'echo REMCOS_LAB_BENIGN_SMOKE' | Out-Null
    if ($LASTEXITCODE -ne 0) { throw 'The harmless child-process check failed.' }
    if ($null -ne $LocalHttpUrl) {
        Invoke-WebRequest -Uri $LocalHttpUrl -UseBasicParsing -MaximumRedirection 0 -TimeoutSec 10 -OutFile (Join-Path $outPath 'download.txt') | Out-Null
    }
    Start-Sleep -Seconds 2
}
[ordered]@{
    run_id = $runId
    evidence_type = 'benign-background'
    description = 'Constructed local benign workload; not representative production traffic.'
    computer = $env:COMPUTERNAME
    started_utc = $started.ToString('o')
    ended_utc = [DateTime]::UtcNow.ToString('o')
    iterations = $iterations
    network_activity = $(if ($null -ne $LocalHttpUrl) { $LocalHttpUrl.AbsoluteUri } else { 'None generated by this helper.' })
} | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $outPath 'session.json') -Encoding UTF8
Write-Host "Benign session recorded in $outPath"
